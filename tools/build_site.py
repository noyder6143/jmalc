#!/usr/bin/env python3
"""Rebuild the class site from the app build sources.

  python3 tools/build_site.py            # copy current builds into the site
  python3 tools/build_site.py --rebuild  # run both app builds first

Adds the site-only parts to each app: PWA tags, config.js + sync.js (optional
cloud accounts), and service worker registration. Also writes meta.js, which the
teacher dashboard uses for level, badge, and test names.
"""
import json, re, subprocess, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from chapters import CHAPTERS, WORKBOOKS, chapters_for
import materials
import build_chapters
SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QUEST_DIR = '/workspace/quest'
LAB_DIR = '/workspace/ic3-practice-app/build'
QUEST_OUT = '/workspace/ic3-computing-fundamentals/fun-course/IC3_Computing_Fundamentals_Quest.html'
LAB_OUT = '/workspace/ic3-practice-app/IC3_CF_Practice_Tests.html'

if '--rebuild' in sys.argv:
    subprocess.run([sys.executable, 'build_quest.py'], cwd=QUEST_DIR, check=True)
    subprocess.run([sys.executable, 'build_app.py'], cwd=LAB_DIR, check=True)

SW = ('<script>if("serviceWorker" in navigator&&location.protocol.indexOf("http")===0)'
      '{addEventListener("load",function(){navigator.serviceWorker.register("sw.js").catch(function(){})})}</script>')
SYNC = '<script src="config.js"></script><script src="sync.js"></script>'

def head(name, theme):
    return (f'<link rel="manifest" href="{name}.webmanifest"><meta name="theme-color" content="{theme}">'
            f'<link rel="icon" href="icons/{name}-192.png"><link rel="apple-touch-icon" href="icons/{name}-180.png">'
            f'<meta name="apple-mobile-web-app-capable" content="yes">\n{SYNC}\n')

def site_page(src, name, theme):
    html = open(src, encoding='utf-8').read()
    m = re.search(r'</title>\n', html)
    assert m, 'no </title>'
    html = html[:m.end()] + head(name, theme) + html[m.end():]
    assert html.rstrip().endswith('</body></html>')
    html = html.rstrip()[:-len('</body></html>')] + SW + '</body></html>\n'
    open(os.path.join(SITE, name + '.html'), 'w', encoding='utf-8').write(html)
    return html

def data_of(html):
    m = re.search(r'<script type="application/json" id="data">(.*?)</script>', html, re.S)
    return json.loads(m.group(1).replace('<\\/', '</'))

q = site_page(QUEST_OUT, 'quest', '#0f1530')
p = site_page(LAB_OUT, 'practice', '#0f7c83')
QD, PD = data_of(q), data_of(p)
tpl = open(os.path.join(QUEST_DIR, 'template.html'), encoding='utf-8').read()
ranks = json.loads(re.search(r"const RANKS=(\[.*?\]);", tpl).group(1).replace("'", '"'))
extra = [{'id': i, 'icon': c, 'name': n} for i, c, n in re.findall(r"\{id:'(\w+)',icon:'([^']+)',name:'([^']+)'", tpl)]
meta = dict(
    ranks=ranks,
    levels=[dict(id=L['id'], name=L['name'], icon=L['icon']) for L in QD['levels']],
    badges=[dict(id='lvl_' + L['id'], icon=L['icon'], name=L['name'] + ' Champ') for L in QD['levels']] + extra,
    tests=[dict(id=t['id'], name=t['name'], kind=t['kind'], program=t['program'], short=t.get('short', t['id'])) for t in PD['tests']]
          + [dict(id='final', name='Final Exam Review', kind='final', program='Final', short='FINAL')],
    domains=PD['domains'],
    chapters=[dict(n=c['n'], title=c['title'], icon=c['icon']) for c in CHAPTERS],
    chItems={b['id']: b['ch'] for b in PD['bank'].values() if b.get('ch')},
    chLessons={str(c['n']): [[x['lv'], x['i']] for x in c['lessons']] for c in QD['chapters']},
    games=[dict(id=g['id'], ch=g['ch'], title=g['title']) for g in __import__('games').GAMES],
)
open(os.path.join(SITE, 'meta.js'), 'w', encoding='utf-8').write(
    '// Generated by tools/build_site.py. Names used by the teacher dashboard.\nwindow.JC_META=' +
    json.dumps(meta, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('quest.html', len(q) // 1024, 'KB; practice.html', len(p) // 1024, 'KB; meta.js tests', len(meta['tests']), 'badges', len(meta['badges']))

# ---- Master Answer Key (teacher dashboard only) ----
LET = 'ABCDEFGH'
TYPEN = {'mc': 'Multiple choice', 'multi': 'Choose all that apply', 'tf': 'True/False', 'yn': 'Yes/No grid', 'dd': 'Dropdown',
         'match': 'Match', 'order': 'Put in order', 'img': 'Click the image', 'sim': 'Simulation'}
TOP2DOM = {}
def lab_ans(b):
    t = b['type']
    if t == 'mc': return [f"{LET[b['ans']]}. {b['opts'][b['ans']]}"]
    if t == 'multi': return [f"{LET[i]}. {b['opts'][i]}" for i in b['ans']]
    if t == 'tf': return ['True' if b['ans'] else 'False']
    if t == 'yn': return [f"{r}: {'Yes' if a else 'No'}" for r, a in zip(b['rows'], b['ans'])]
    if t == 'dd': return [f"Blank {i+1}: {o[a]}" for i, (o, a) in enumerate(zip(b['blanks'], b['ans']))]
    if t == 'match': return [f"{l} = {r}" for l, r in zip(b['left'], b['right'])]
    if t == 'order': return [f"{i+1}. {s}" for i, s in enumerate(b['steps'])]
    if t == 'img': return [f"Click the {b['ansLabel']}"]
    if t == 'sim':
        out = []
        for w, lab in (('w10', 'Windows 10 / Office 2016'), ('w7', 'Windows 7 / Office 2013')):
            if w in b.get('variants', {}):
                out += [f"{lab}, step {i+1} [{s['screen']}]: " + (f'type "{s["a"]}"' if s.get('input') else s['opts'][s['a']]) for i, s in enumerate(b['variants'][w])]
        return out
    return []
tname = {t['id']: t.get('short', t['id']) for t in PD['tests']}
key = []
for b in PD['bank'].values():
    q = b['q'] + ((' Sentence: ' + b['text']) if b['type'] == 'dd' and b.get('text') else '')
    opts = b['opts'] if b['type'] in ('mc', 'multi') else []
    fin = b['type'] in PD['final']['types'] and bool(b.get('dom'))
    where = [tname.get(t, t) for t in b.get('tests', [])] + (['Final Exam Review pool'] if fin else [])
    new = b.get('tt') == 'CH'
    where = (['New for Ch 1-7'] if new else []) + where + [f"Chapter {n} Quiz" for n in b.get('ch', [])]
    key.append(dict(app='lab', dom=str(b.get('dom', '')), od=b.get('od', []), kind=TYPEN.get(b['type'], b['type']), id=b['id'],
                    q=q, opts=opts, a=lab_ans(b), why=(b.get('why') or '') + ((' On GMetrix, expect: ' + b['flag']) if b.get('flag') else ''),
                    where=where, fin=fin, ch=b.get('ch', []), new=new))
for L in QD['levels']:
    d = str(L['od']); lv = f"Level {L['n']}: {L['name']}"
    for i, x in enumerate(L['quiz'], 1):
        key.append(dict(app='quest', dom=d, od=x.get('od', []), kind='Quest quiz', id=f"{L['id']}-q{i}", q=x['q'], opts=x['c'],
                        a=[f"{LET[x['a']]}. {x['c'][x['a']]}"], why=x.get('why', ''), where=[lv], ch=chapters_for(x.get('od', []))))
    for i, s in enumerate(L['sims'], 1):
        key.append(dict(app='quest', dom=d, od=s.get('od', []), kind='Quest simulation', id=f"{L['id']}-sim{i}", q=s['title'] + '. ' + s['prompt'], opts=[],
                        a=[f"Step {j+1} [{st['screen']}] {st['q']} " + ('type "' + str(st['a']) + '"' if 'opts' not in st else st['opts'][st['a']]) for j, st in enumerate(s['steps'])],
                        why=s.get('today', ''), where=[lv], ch=chapters_for(s.get('od', []))))
    for i, g in enumerate(L['games'], 1):
        if 'pairs' in g: a = [f"{l} = {r}" for l, r in g['pairs']]
        else: a = [f"{it[0]}: {g['bins'][it[1]]}" + (f" ({it[2]})" if len(it) > 2 and it[2] else '') for it in g['items']]
        key.append(dict(app='quest', dom=d, od=g.get('od', []), kind='Quest game (' + g['type'] + ')', id=f"{L['id']}-game{i}", q=g['title'],
                        opts=[], a=a, why='', where=[lv], ch=chapters_for(g.get('od', []))))
js = json.dumps(key, ensure_ascii=False, separators=(',', ':'))
open(os.path.join(SITE, 'answerkey.js'), 'w', encoding='utf-8').write(
    '// Generated by tools/build_site.py. Master Answer Key for the teacher dashboard.\nwindow.JC_KEY=' + js + ';\n')
from collections import Counter
print('answerkey.js', Counter(k['app'] for k in key), 'final pool', sum(1 for k in key if k.get('fin')))

